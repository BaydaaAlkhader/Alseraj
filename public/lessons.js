function openLessonPlayer(courseId, lessonIndex) {
  appState.currentCourseId = courseId;
  appState.currentLessonIndex = lessonIndex;

  const course = APP_DATA.courses.find((c) => c.id === courseId);
  if (!course || !course.lessons[lessonIndex]) return;

  const lesson = course.lessons[lessonIndex];

  // Breadcrumbs
  document.getElementById("playerBreadcrumbCat").textContent =
    course.categoryName;
  document.getElementById("playerBreadcrumbCourse").textContent = course.title;
  document.getElementById("playerBreadcrumbLesson").textContent = lesson.title;

  // Header and Video
  document.getElementById("playerLessonTag").textContent =
    `الدرس ${lessonIndex + 1} من ${course.lessons.length}`;
  document.getElementById("playerLessonTitle").textContent = lesson.title;
  document.getElementById("playerScholarName").textContent = course.scholarName;
  document.getElementById("videoIframe").src = lesson.embedUrl;
  document.getElementById("playerLessonDesc").textContent =
    lesson.desc || course.description;

  // Notes
  const noteKey = `${courseId}_${lessonIndex}`;
  document.getElementById("playerNotesInput").value =
    appState.userData.notes[noteKey] || "";

  // Buttons UI State
  updatePlayerActionButtons();
  renderPlayerSidebar();

  switchView("lessonPlayerView");
}

