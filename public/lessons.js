/* =========================================================
   الحسابات والإحصائيات
   ========================================================= */
function isLessonCompleted(courseId, lessonIndex) {
  return !!appState.userData.completedLessons[`${courseId}_${lessonIndex}`];
}

function getCompletedLessonsCount(courseId) {
  const course = APP_DATA.courses.find((c) => c.id === courseId);
  if (!course) return 0;
  return course.lessons.reduce(
    (acc, _, idx) => acc + (isLessonCompleted(courseId, idx) ? 1 : 0),
    0,
  );
}

function getCourseProgressPercentage(courseId) {
  const course = APP_DATA.courses.find((c) => c.id === courseId);
  if (!course || course.lessons.length === 0) return 0;
  const completed = getCompletedLessonsCount(courseId);
  return Math.round((completed / course.lessons.length) * 100);
}

function getLastWatchedLessonIndex(courseId) {
  const course = APP_DATA.courses.find((c) => c.id === courseId);
  if (!course) return 0;
  for (let i = course.lessons.length - 1; i >= 0; i--) {
    if (isLessonCompleted(courseId, i)) {
      return Math.min(i + 1, course.lessons.length - 1);
    }
  }
  return 0;
}

function updateOverallStats() {
  let totalLessons = 0;
  let completedLessons = 0;
  let completedPaths = 0;

  APP_DATA.courses.forEach((course) => {
    totalLessons += course.lessons.length;
    const completedInCourse = getCompletedLessonsCount(course.id);
    completedLessons += completedInCourse;
    if (
      completedInCourse === course.lessons.length &&
      course.lessons.length > 0
    ) {
      completedPaths++;
    }
  });

  const overallPercent =
    totalLessons > 0 ? Math.round((completedLessons / totalLessons) * 100) : 0;

  const circle = document.getElementById("mainProgressCircle");
  if (circle) {
    circle.style.background = `conic-gradient(#1b3b2b ${overallPercent * 3.6}deg, #e5e7eb ${overallPercent * 3.6}deg)`;
  }

  document.getElementById("overallPercentText").textContent =
    `${overallPercent}%`;
  document.getElementById("completedPathsCount").textContent = completedPaths;
  document.getElementById("completedLessonsCount").textContent =
    completedLessons;
  document.getElementById("remainingLessonsCount").textContent =
    totalLessons - completedLessons;
}


