async function fetchUserProgressFromServer() {
  const token = localStorage.getItem('userToken'); // جلب التوكن الخاص بالمستخدم الحالي
  
  if (!token) {
    console.warn("لم يتم العثور على توكن، يرجى تسجيل الدخول");
    return;
  }

  try {
    const response = await fetch('/api/user/progress', {
      method: 'GET',
      headers: {
        'Authorization': `Bearer ${token}`, // إرسال التوكن للسيرفر ليعرف من هو المستخدم
        'Content-Type': 'application/json'
      }
    });

    if (response.ok) {
      const data = await response.json();
      if (data.success && data.progress) {
        
        // تحويل البيانات القادمة من مصفوفة السيرفر (courseProgress) إلى صيغة يفهمها كود الفرونت إند الحالي
        appState.userData.completedLessons = {};
        
        data.progress.forEach(course => {
          // بناءً على عدد الدروس المكتملة في السيرفر، نملأ كائن الفرونت إند ليعكس التقدم بشكل صحيح
          for (let i = 0; i < course.completedLessons; i++) {
            appState.userData.completedLessons[`${course.courseId}_${i}`] = true;
          }
        });

        // حفظ التزامن في الذاكرة المحلية المتوافقة مع بقية دوال الصفحة
        saveUserData();
      }
    } else {
      console.error("فشل السيرفر في إعادة التقدم الصحيح:", response.statusText);
    }
  } catch (error) {
    console.error("خطأ أثناء الاتصال بالسيرفر لتزامن الدروس:", error);
  }
}
// دالة مخصصة لصفحة الدروس لتحديث الاسم وأول حرف في الشريط العلوي
function updateUserNavbarUI(name) {
  const nameDisplay = document.getElementById("userNameDisplay");
  const avatarDisplay = document.getElementById("userAvatar");

  if (name && name !== "null" && name !== "undefined") {
    if (nameDisplay) nameDisplay.textContent = name;
    // أخذ الحرف الأول، إزالة المسافات، وتحويله لحرف كبير
    if (avatarDisplay)
      avatarDisplay.textContent = name.trim().charAt(0).toUpperCase();
  } else {
    // قيم افتراضية في حال عدم تسجيل الدخول
    if (nameDisplay) nameDisplay.textContent = "مستخدم";
    if (avatarDisplay) avatarDisplay.textContent = "م";
  }
}
function setupEventListeners() {
  // السلايدر أفقي
  const slideRightBtn = document.getElementById("slideRightBtn");
  const slideLeftBtn = document.getElementById("slideLeftBtn");
  const carousel = document.getElementById("featuredCoursesContainer");

  if (slideRightBtn && carousel) {
    slideRightBtn.addEventListener("click", () =>
      carousel.scrollBy({ left: 300, behavior: "smooth" }),
    );
  }
  if (slideLeftBtn && carousel) {
    slideLeftBtn.addEventListener("click", () =>
      carousel.scrollBy({ left: -300, behavior: "smooth" }),
    );
  }

  // تنقل الدروس بالداخل (السابق/التالي)
  const prevBtn = document.getElementById("prevLessonBtn");
  const nextBtn = document.getElementById("nextLessonBtn");

  if (prevBtn) prevBtn.addEventListener("click", () => navigateLesson(-1));
  if (nextBtn) nextBtn.addEventListener("click", () => navigateLesson(1));
}

